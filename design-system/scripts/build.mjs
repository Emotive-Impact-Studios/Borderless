// Builds dist/ from tokens/source.mjs: tokens.json, tokens.css, tokens.ts, BorderlessTokens.swift.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as T from '../tokens/source.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist');
mkdirSync(out, { recursive: true });

const kebab = s => s.replace(/[A-Z]/g, m => '-' + m.toLowerCase());
const px = n => (n === 0 ? '0' : `${n}px`);

// ---------- JSON ----------
writeFileSync(join(out, 'tokens.json'), JSON.stringify({
  meta: T.meta, space: T.space, radius: T.radius, font: T.font, type: T.type, motion: T.motion,
  owners: T.owners, themes: T.themes, elevation: T.elevation,
}, null, 2) + '\n');

// ---------- CSS ----------
const css = [];
css.push('/* Generated by design-system/scripts/build.mjs. Do not edit. */');
css.push(':root {');
css.push('  --bl-wall-scale: 1;');
for (const [k, v] of Object.entries(T.space)) css.push(`  --bl-space-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(T.radius)) css.push(`  --bl-radius-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(T.font)) css.push(`  --bl-font-${k}: ${v};`);
for (const [ramp, styles] of Object.entries(T.type)) {
  if (ramp === 'min') continue;
  for (const [name, [size, lh, weight, track]] of Object.entries(styles)) {
    const scale = ramp === 'wall' ? ' * var(--bl-wall-scale)' : '';
    css.push(`  --bl-${ramp}-${kebab(name)}-size: calc(${size}px${scale});`);
    css.push(`  --bl-${ramp}-${kebab(name)}-line: calc(${lh}px${scale});`);
    css.push(`  --bl-${ramp}-${kebab(name)}-weight: ${weight};`);
    css.push(`  --bl-${ramp}-${kebab(name)}-tracking: ${track}em;`);
  }
}
for (const [k, v] of Object.entries(T.motion.duration)) css.push(`  --bl-dur-${k}: ${v}ms;`);
for (const [k, v] of Object.entries(T.motion.easing)) css.push(`  --bl-ease-${k}: ${v};`);
css.push(`  --bl-focus-scale: ${T.motion.focusScale};`);
css.push('}');

function themeBlock(name, t) {
  const o = T.owners[t.mode];
  const lines = [];
  lines.push(`  color-scheme: ${t.mode};`);
  for (const [k, v] of Object.entries(t.color)) if (k !== 'shadow') lines.push(`  --bl-${kebab(k)}: ${v};`);
  lines.push(`  --bl-shadow-rgb: ${t.color.shadow};`);
  for (const [k, v] of Object.entries(o)) lines.push(`  --bl-owner-${k}: ${v};`);
  lines.push(`  --bl-glass-fill: ${t.glass.fill};`);
  lines.push(`  --bl-glass-stroke: ${t.glass.stroke};`);
  lines.push(`  --bl-glass-highlight: ${t.glass.highlight};`);
  lines.push(`  --bl-glass-blur: ${t.glass.blur}px;`);
  lines.push(`  --bl-glass-saturate: ${t.glass.saturate};`);
  for (const [k, v] of Object.entries(T.elevation)) lines.push(`  --bl-elev-${k}: ${v.replaceAll('rgba({shadow}', 'rgba(var(--bl-shadow-rgb)')};`);
  lines.push(`  --bl-font-heading: ${t.displayFont ?? 'var(--bl-font-display)'};`);
  const rs = t.radiusScale ?? 1;
  lines.push(`  --bl-radius-scale: ${rs};`);
  lines.push(`  --bl-numbered: ${t.numbered ? 1 : 0};`);
  return lines.join('\n');
}
// Whiteboard is the default; the others apply with data-bl-theme on any element.
css.push(`:root, [data-bl-theme="whiteboard"] {\n${themeBlock('whiteboard', T.themes.whiteboard)}\n}`);
for (const [name, t] of Object.entries(T.themes)) {
  if (name === 'whiteboard') continue;
  css.push(`[data-bl-theme="${name}"] {\n${themeBlock(name, t)}\n}`);
}
css.push(`@media (min-width: 3000px) { .bl-wall { --bl-wall-scale: 2; } }`);
css.push(`@media (prefers-reduced-motion: reduce) { :root { --bl-dur-travel: 0ms; --bl-dur-arrival: 150ms; --bl-dur-ambient: 0ms; } }`);
writeFileSync(join(out, 'tokens.css'), css.join('\n') + '\n');

// ---------- TypeScript (React Native and web) ----------
const ts = `// Generated by design-system/scripts/build.mjs. Do not edit.
export const tokens = ${JSON.stringify({ space: T.space, radius: T.radius, font: T.font, type: T.type, motion: T.motion, owners: T.owners, themes: T.themes, elevation: T.elevation }, null, 2)} as const;
export type ThemeName = keyof typeof tokens.themes;
export type OwnerColour = keyof typeof tokens.owners.light;
export const ownerOrder: OwnerColour[] = ${JSON.stringify(Object.keys(T.owners.light))};
export default tokens;
`;
writeFileSync(join(out, 'tokens.ts'), ts);

// ---------- Swift (Mac app, SwiftUI) ----------
const hex = h => {
  const m = h.match(/^#([0-9a-f]{6})$/i);
  if (m) { const n = parseInt(m[1], 16); return `Color(red: ${((n >> 16) & 255) / 255}, green: ${((n >> 8) & 255) / 255}, blue: ${(n & 255) / 255})`; }
  const r = h.match(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/);
  if (r) return `Color(red: ${r[1] / 255}, green: ${r[2] / 255}, blue: ${r[3] / 255}).opacity(${r[4]})`;
  throw new Error('colour ' + h);
};
const sw = [];
sw.push('// Generated by design-system/scripts/build.mjs. Do not edit.');
sw.push('import SwiftUI\n');
sw.push('public enum BL {');
sw.push('  public enum Space {');
for (const [k, v] of Object.entries(T.space)) sw.push(`    public static let s${k}: CGFloat = ${v}`);
sw.push('  }');
sw.push('  public enum Radius {');
for (const [k, v] of Object.entries(T.radius)) sw.push(`    public static let ${k}: CGFloat = ${v}`);
sw.push('  }');
sw.push('  public enum Duration {');
for (const [k, v] of Object.entries(T.motion.duration)) sw.push(`    public static let ${k}: Double = ${v / 1000}`);
sw.push('  }');
sw.push('  public enum Springs {');
for (const [k, v] of Object.entries(T.motion.spring)) sw.push(`    public static let ${k} = Animation.spring(response: ${v.response}, dampingFraction: ${v.damping})`);
sw.push('  }');
sw.push('  public struct Theme {');
const ck = Object.keys(T.themes.whiteboard.color).filter(k => k !== 'shadow');
for (const k of ck) sw.push(`    public let ${k}: Color`);
sw.push('    public let owners: [Color]');
sw.push('  }');
sw.push('  public enum Themes {');
for (const [name, t] of Object.entries(T.themes)) {
  const args = ck.map(k => `${k}: ${hex(t.color[k])}`).join(',\n      ');
  const ow = Object.values(T.owners[t.mode]).map(hex).join(', ');
  sw.push(`    public static let ${name} = Theme(\n      ${args},\n      owners: [${ow}])`);
}
sw.push('  }');
sw.push('}');
writeFileSync(join(out, 'BorderlessTokens.swift'), sw.join('\n') + '\n');

console.log('Built tokens.json, tokens.css, tokens.ts, BorderlessTokens.swift');

// ---------- Showcase (self-contained page: component library reference) ----------
import { readFileSync } from 'node:fs';
const src = readFileSync(join(root, 'components', 'index.src.html'), 'utf8');
const showcase = src
  .replace('<!--TOKENS-->', () => `<style>\n${readFileSync(join(out, 'tokens.css'), 'utf8')}</style>`)
  .replace('<!--COMPONENTS-->', () => `<style>\n${readFileSync(join(root, 'components', 'components.css'), 'utf8')}</style>`)
  .replace('/*TOKENJSON*/null', () => JSON.stringify({ themes: T.themes, owners: T.owners, type: T.type, space: T.space, radius: T.radius, motion: T.motion }));
writeFileSync(join(out, 'showcase.html'), showcase);
console.log('Built showcase.html');
