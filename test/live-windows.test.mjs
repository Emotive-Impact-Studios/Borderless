import test from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import { fixture, room, participant, wall, command, snapshot, connect, event, request } from "./helpers.mjs";

const stream = async (app, actor) => (await snapshot(app, actor)).streams[0];

test("personal live-window access needs an owner offer and the invited person's current acceptance", async t => {
  const app = await fixture(t), { admin } = await room(app);
  const owner = await participant(app, admin, "Emma"), viewer = await participant(app, admin, "Alex"), other = await participant(app, admin, "Another person");
  const { actor: display } = await wall(app, admin), another = await room(app);
  await command(app, owner, "stream.start");
  const screen = await stream(app, owner), reference = { streamId: screen.id, deviceId: viewer.id };
  assert.equal((await command(app, admin, "stream.invite", reference)).status, 403);
  assert.equal((await command(app, other, "stream.invite", reference)).status, 403);
  assert.equal((await command(app, display, "stream.invite", reference)).status, 403);
  assert.equal((await command(app, owner, "stream.invite", { ...reference, deviceId: another.admin.id })).status, 404);
  assert.equal((await command(app, owner, "stream.invite", { ...reference, deviceId: display.id })).status, 404);
  const offer = { ...reference, commandId: "offer-once" };
  assert.equal((await command(app, owner, "stream.invite", offer)).status, 200);
  assert.equal((await command(app, owner, "stream.invite", offer)).status, 200);
  let own = await stream(app, owner), target = await stream(app, viewer);
  assert.equal(own.invitations.length, 1);
  assert.equal(target.canReceive, false);
  assert.deepEqual((await stream(app, other)).invitations, []);
  assert.deepEqual((await stream(app, admin)).invitations, []);
  assert.equal((await stream(app, other)).receivers, undefined);
  const invitationId = target.invitations[0].id;
  const accept = { streamId: screen.id, invitationId, deviceId: viewer.id };
  assert.equal((await command(app, other, "stream.accept", accept)).status, 403);
  assert.equal((await command(app, display, "stream.accept", accept)).status, 403);
  assert.equal((await command(app, viewer, "stream.accept", { ...accept, commandId: "accept-once" })).status, 200);
  assert.equal((await command(app, viewer, "stream.accept", { ...accept, commandId: "accept-once" })).status, 200);
  assert.equal((await stream(app, viewer)).canReceive, true);
  assert.ok((await stream(app, owner)).receivers.includes(viewer.id));
  assert.equal((await command(app, admin, "stream.revoke", accept)).status, 403);
  assert.equal((await command(app, owner, "stream.revoke", accept)).status, 200);
  assert.equal((await command(app, viewer, "stream.accept", { ...accept, commandId: "accept-once" })).status, 200);
  assert.equal((await stream(app, viewer)).canReceive, false);
  await command(app, owner, "stream.invite", reference);
  const fresh = (await stream(app, viewer)).invitations[0].id;
  assert.notEqual(fresh, invitationId);
  assert.equal((await command(app, viewer, "stream.accept", accept)).status, 409);
  assert.equal((await command(app, viewer, "stream.accept", { streamId: screen.id, invitationId: fresh })).status, 200);
  assert.equal((await command(app, viewer, "stream.decline", { streamId: screen.id, invitationId: fresh })).status, 200);
  assert.equal((await stream(app, viewer)).canReceive, false);
  assert.equal(app.store.verifyAudit().valid, true);
});

test("accepted participants receive targeted signals, and receiver closure does not stop the capture connection", async t => {
  const app = await fixture(t), { admin } = await room(app);
  const owner = await participant(app, admin), viewer = await participant(app, admin, "Viewer");
  const source = await connect(app, owner), ownerPreview = await connect(app, owner), receiver = await connect(app, viewer), anotherTab = await connect(app, viewer);
  t.after(() => [source, ownerPreview, receiver, anotherTab].forEach(socket => socket.terminate()));
  const captureId = (await event(source, e => e.type === "hello")).connectionId;
  const receiverId = (await event(receiver, e => e.type === "hello")).connectionId;
  await command(app, owner, "stream.start", { connectionId: captureId });
  const screen = await stream(app, owner);
  const ready = { type: "rtc", streamId: screen.id, targetId: owner.id, targetConnectionId: captureId, kind: "ready" };
  receiver.send(JSON.stringify(ready));
  assert.match((await event(receiver, e => e.type === "error")).error, /invitation/);
  await command(app, owner, "stream.invite", { streamId: screen.id, deviceId: viewer.id });
  const invitationId = (await stream(app, viewer)).invitations[0].id;
  await command(app, viewer, "stream.accept", { streamId: screen.id, invitationId });
  receiver.send(JSON.stringify(ready));
  assert.equal((await event(source, e => e.type === "rtc" && e.kind === "ready")).fromConnectionId, receiverId);
  const offer = { type: "rtc", streamId: screen.id, targetId: viewer.id, targetConnectionId: receiverId, kind: "offer", payload: { sdp: "one-connection-only" } };
  ownerPreview.send(JSON.stringify(offer));
  assert.match((await event(ownerPreview, e => e.type === "error")).error, /active capture connection/);
  source.send(JSON.stringify(offer));
  assert.equal((await event(receiver, e => e.type === "rtc" && e.kind === "offer")).payload.sdp, "one-connection-only");
  assert.equal(anotherTab.messages.some(e => e.type === "rtc"), false);
  receiver.send(JSON.stringify({ ...ready, kind: "answer", payload: { sdp: "an-answer" } }));
  assert.equal((await event(source, e => e.type === "rtc" && e.kind === "answer")).fromId, viewer.id);
  const closed = once(receiver, "close"); receiver.close(); await closed;
  assert.equal((await event(source, e => e.type === "rtc.peer.left")).connectionId, receiverId);
  assert.equal((await snapshot(app, owner)).streams.length, 1);
  await command(app, owner, "stream.revoke", { streamId: screen.id, invitationId });
  anotherTab.send(JSON.stringify(ready));
  assert.match((await event(anotherTab, e => e.type === "error")).error, /invitation/);
  const ownerClosed = once(source, "close"); source.close(); await ownerClosed;
  await event(ownerPreview, e => e.type === "state" && e.state.streams.length === 0);
  assert.equal((await snapshot(app, viewer)).streams.length, 0);
});

test("live-window offers expire, and recipient logout/expiry retires their capture access", async t => {
  const app = await fixture(t), { admin, roomId } = await room(app);
  const owner = await participant(app, admin), viewer = await participant(app, admin, "Expiring viewer");
  await command(app, owner, "stream.start");
  const screen = await stream(app, owner), offer = { streamId: screen.id, deviceId: viewer.id };
  await command(app, owner, "stream.invite", offer);
  const old = (await stream(app, viewer)).invitations[0].id;
  let stored = app.store.room(roomId);
  stored.state.streams[0].invitations[0].expiresAt = Date.now() - 1;
  app.store.saveRoom(stored);
  assert.equal((await command(app, viewer, "stream.accept", { streamId: screen.id, invitationId: old })).status, 410);
  assert.equal((await stream(app, viewer)).invitations.length, 0);
  await command(app, owner, "stream.invite", offer);
  let invitationId = (await stream(app, viewer)).invitations[0].id;
  await command(app, viewer, "stream.accept", { streamId: screen.id, invitationId });
  await request(app, `/api/rooms/${roomId}/logout`, { method: "POST", actor: viewer, data: {} });
  assert.equal((await stream(app, owner)).invitations.length, 0);
  assert.equal((await snapshot(app, owner)).streams.length, 1);
  const replacement = await participant(app, admin, "Same name, new identity");
  assert.equal((await stream(app, replacement)).canReceive, false);
  await command(app, owner, "stream.invite", { streamId: screen.id, deviceId: replacement.id });
  invitationId = (await stream(app, replacement)).invitations[0].id;
  await command(app, replacement, "stream.accept", { streamId: screen.id, invitationId });
  app.store.db.prepare("UPDATE sessions SET expires=? WHERE device_id=?").run(Date.now() - 1, replacement.id);
  app.store.retireInactiveSessions();
  assert.equal((await stream(app, owner)).receivers.includes(replacement.id), false);
  assert.equal((await stream(app, owner)).invitations.length, 0);
  await command(app, admin, "room.lock", { locked: true });
  assert.equal((await snapshot(app, owner)).streams.length, 0);
});

test("live-window routes serve only an external-script shell and keep room state authenticated", async t => {
  const app = await fixture(t), { admin, roomId } = await room(app);
  await command(app, admin, "stream.start");
  const screen = await stream(app, admin), path = `/screen/${roomId}/${screen.id}`;
  const shell = await request(app, path);
  assert.equal(shell.status, 200);
  assert.match(shell.body.toString(), /src="\/js\/screen.js"/);
  assert.doesNotMatch(shell.body.toString(), /<script[^>]*>\s*[^<\s]/i);
  assert.match(shell.response.headers.get("content-security-policy"), /script-src 'self'/);
  assert.equal((await request(app, `/api/rooms/${roomId}/state`)).status, 401);
  assert.equal((await request(app, `/screen/${roomId}/not-a-stream`)).status, 404);
});

test("a private live window reaches only its owner and accepted invitees, never the leader or Wall", async t => {
  const app = await fixture(t), { admin } = await room(app);
  const owner = await participant(app, admin, "Designer"), viewer = await participant(app, admin, "Colleague"), other = await participant(app, admin, "Bystander");
  const { actor: display } = await wall(app, admin);
  const leaderSocket = await connect(app, admin), displaySocket = await connect(app, display), source = await connect(app, owner);
  t.after(() => [leaderSocket, displaySocket, source].forEach(socket => socket.terminate()));
  const captureId = (await event(source, e => e.type === "hello")).connectionId;
  assert.equal((await command(app, owner, "stream.start", { connectionId: captureId, audience: "everyone" })).status, 400);
  assert.equal((await command(app, owner, "stream.start", { connectionId: captureId, audience: "private" })).status, 200);
  const screen = await stream(app, owner);
  assert.equal(screen.audience, "private");
  for (const actor of [admin, display, viewer, other]) assert.equal((await snapshot(app, actor)).streams.length, 0);
  assert.deepEqual(screen.receivers, [owner.id]);
  // Knowing the identifier grants nothing: geometry, stop and signalling all refuse.
  assert.equal((await command(app, admin, "stream.stop", { streamId: screen.id })).status, 404);
  assert.equal((await command(app, admin, "stream.move", { streamId: screen.id, version: screen.version, x: 0, y: 0 })).status, 404);
  const ready = { type: "rtc", streamId: screen.id, targetId: owner.id, targetConnectionId: captureId, kind: "ready" };
  leaderSocket.send(JSON.stringify(ready));
  assert.match((await event(leaderSocket, e => e.type === "error")).error, /not found/i);
  displaySocket.send(JSON.stringify(ready));
  assert.match((await event(displaySocket, e => e.type === "error")).error, /not found/i);
  await command(app, owner, "stream.invite", { streamId: screen.id, deviceId: viewer.id });
  const invited = await stream(app, viewer);
  assert.equal(invited.canReceive, false);
  assert.equal((await snapshot(app, other)).streams.length, 0);
  await command(app, viewer, "stream.accept", { streamId: screen.id, invitationId: invited.invitations[0].id });
  assert.equal((await stream(app, viewer)).canReceive, true);
  assert.deepEqual((await stream(app, owner)).receivers.sort(), [owner.id, viewer.id].sort());
  for (const actor of [admin, display, other]) assert.equal((await snapshot(app, actor)).streams.length, 0);
  assert.equal(source.messages.some(e => e.type === "rtc" && e.kind === "ready"), false);
  assert.equal((await command(app, owner, "stream.stop", { streamId: screen.id })).status, 200);
  assert.equal(app.store.verifyAudit().valid, true);
});

test("a room live window still reaches the leader and Wall by default", async t => {
  const app = await fixture(t), { admin } = await room(app);
  const owner = await participant(app, admin);
  const { actor: display } = await wall(app, admin);
  await command(app, owner, "stream.start");
  const screen = await stream(app, owner);
  assert.equal(screen.audience, "room");
  assert.equal((await stream(app, admin)).canReceive, true);
  assert.equal((await stream(app, display)).canReceive, true);
});
